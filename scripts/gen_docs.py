# ---------------------------------------------------------------------------
# Markdown helpers
# ---------------------------------------------------------------------------


def cell(text: Any) -> str:
    """A value safe inside a Markdown table cell."""
    s = "" if text is None else str(text)
    s = " ".join(s.split())
    return s.replace("|", "\\|")


def code(text: Any) -> str:
    s = str(text)
    fence = "``" if "`" in s else "`"
    pad = " " if s.startswith("`") or s.endswith("`") else ""
    return f"{fence}{pad}{s}{pad}{fence}"


def table(header: list[str], rows: Iterable[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def anchor(title: str) -> str:
    """GitHub-style heading anchor."""
    keep = []
    for ch in title.strip().lower():
        if ch.isalnum() or ch in "-_":
            keep.append(ch)
        elif ch == " ":
            keep.append("-")
    return "".join(keep)


# ---------------------------------------------------------------------------
# JSON schema rendering
# ---------------------------------------------------------------------------


def _ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def type_of(schema: Any) -> str:
    """Short, readable type of a JSON schema node (``$ref`` targets are named, not expanded)."""
    if not isinstance(schema, dict) or not schema:
        return "any"
    if "$ref" in schema:
        return f"`{_ref_name(schema['$ref'])}`"
    if "const" in schema:
        return code(json.dumps(schema["const"]))
    if "enum" in schema:
        return " | ".join(code(json.dumps(v)) for v in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts: list[str] = []
            for sub in schema[key]:
                rendered = type_of(sub)
                if rendered not in parts:
                    parts.append(rendered)
            return " | ".join(parts)
    if "allOf" in schema and len(schema["allOf"]) == 1:
        return type_of(schema["allOf"][0])
    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(type_of({**schema, "type": x}) for x in t)
    if t == "array":
        items = schema.get("items")
        return f"array of {type_of(items)}" if items else "array"
    if t == "object":
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict) and extra:
            return f"object of {type_of(extra)}"
        return "object"
    if t in ("integer", "number"):
        lo = schema.get("minimum", schema.get("exclusiveMinimum"))
        hi = schema.get("maximum", schema.get("exclusiveMaximum"))
        if lo is not None or hi is not None:
            return f"{t} ({'' if lo is None else lo}..{'' if hi is None else hi})"
        return str(t)
    if t == "string" and schema.get("format"):
        return f"string ({schema['format']})"
    return str(t) if t else "any"


def _refs(schema: Any) -> Iterator[str]:
    if isinstance(schema, dict):
        if "$ref" in schema:
            yield _ref_name(schema["$ref"])
        for v in schema.values():
            yield from _refs(v)
    elif isinstance(schema, list):
        for v in schema:
            yield from _refs(v)


def reachable_defs(root: Any, defs: dict[str, Any]) -> list[str]:
    """``$defs`` names reachable from ``root``, in first-reference order."""
    seen: list[str] = []
    stack = list(_refs(root))
    stack.reverse()
    while stack:
        name = stack.pop()
        if name in seen or name not in defs:
            continue
        seen.append(name)
        stack.extend(reversed(list(_refs(defs[name]))))
    return seen


def default_str(prop: dict[str, Any]) -> str:
    if "default" not in prop:
        return ""
    return code(json.dumps(prop["default"], ensure_ascii=False))


def property_rows(schema: dict[str, Any], *, with_description: bool = True) -> list[list[str]]:
    required = set(schema.get("required") or [])
    rows = []
    for name, prop in (schema.get("properties") or {}).items():
        row = [code(name), cell(type_of(prop)), "yes" if name in required else "", default_str(prop)]
        if with_description:
            row.append(cell(prop.get("description", "")))
        rows.append(row)
    return rows


