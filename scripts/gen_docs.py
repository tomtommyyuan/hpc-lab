# Typer >= 0.27 vendors its own copy of Click, so these helpers use duck typing (``param_type_name``,
# ``commands``) instead of ``isinstance`` checks against ``click`` classes.


def _is_option(p: Any) -> bool:
    return getattr(p, "param_type_name", None) == "option"


def _is_argument(p: Any) -> bool:
    return getattr(p, "param_type_name", None) == "argument"


def _is_group(cmd: Any) -> bool:
    return isinstance(getattr(cmd, "commands", None), dict)


def _subcommands(cmd: Any) -> list[tuple[str, Any]]:
    """Visible subcommands in registration order (the order ``hpclab --help`` shows)."""
    return [(n, c) for n, c in cmd.commands.items() if _visible(c)]


def _param_type(p: Any) -> str:
    t = p.type
    choices = getattr(t, "choices", None)
    if choices:
        return " | ".join(code(c) for c in choices)
    if getattr(p, "is_flag", False):
        return "flag"
    name = str(getattr(t, "name", "") or "")
    if name.endswith("range"):
        base = name.removesuffix(" range")
        lo = "" if getattr(t, "min", None) is None else t.min
        hi = "" if getattr(t, "max", None) is None else t.max
        return f"{base} ({lo}..{hi})"
    return {"str": "text", "text": "text", "integer": "int", "boolean": "bool"}.get(name, name or "text")


def _param_default(p: Any) -> str:
    if getattr(p, "show_default", None) is False:
        return ""
    d = p.default
    if callable(d) or d is None:
        return ""
    if getattr(p, "is_flag", False) and not d:
        return ""
    if isinstance(d, list | tuple | str) and not d:
        return ""
    if isinstance(d, Path):
        d = str(d)
    return code(d)


def _param_names(p: Any) -> str:
    """``--yes, -y``; an on/off flag pair as ``--sim / --no-sim``."""
    names = ", ".join(code(n) for n in p.opts)
    if p.secondary_opts:
        names += " / " + ", ".join(code(n) for n in p.secondary_opts)
    return names


def _help_first_line(cmd: Any) -> str:
    text = inspect.cleandoc(cmd.help or "")
    return text.split("\n\n", 1)[0].replace("\n", " ").strip()


def _visible(obj: Any) -> bool:
    return not getattr(obj, "hidden", False)


def _usage(path: list[str], cmd: Any) -> str:
    parts = list(path)
    if _is_group(cmd):
        return " ".join([*parts, "COMMAND [ARGS]..."])
    if any(_is_option(p) and _visible(p) and p.name != "help" for p in cmd.params):
        parts.append("[OPTIONS]")
    for p in cmd.params:
        if _is_argument(p):
            name = str(p.name).upper() + ("..." if p.nargs == -1 else "")
            parts.append(name if p.required else f"[{name}]")
    return " ".join(parts)


def _option_rows(opts: list[Any], *, with_required: bool = True) -> list[list[str]]:
    rows = []
    for p in opts:
        desc = cell(getattr(p, "help", "") or "")
        envvar = p.envvar if isinstance(p.envvar, str) else None
        if envvar:
            desc = (desc + " " if desc else "") + f"(env {code(envvar)})"
        if getattr(p, "multiple", False) and "repeatable" not in desc.lower():
            desc = (desc + " " if desc else "") + "Repeatable."
        row = [_param_names(p), cell(_param_type(p))]
        if with_required:
            row.append("yes" if p.required else "")
        row += [_param_default(p), desc]
        rows.append(row)
    return rows


def _command_section(path: list[str], cmd: Any, level: int) -> list[str]:
    title = " ".join(path)
    out = [f"{'#' * level} {title}", "", f"`{_usage(path, cmd)}`", ""]
    help_text = inspect.cleandoc(cmd.help or "")
    if help_text:
        out += [help_text, ""]
    args = [p for p in cmd.params if _is_argument(p)]
    opts = [p for p in cmd.params if _is_option(p) and _visible(p) and p.name != "help"]
    if args:
        rows = [
            [
                code(str(p.name).upper()),
                cell(_param_type(p)),
                "yes" if p.required else "",
                _param_default(p),
                cell(getattr(p, "help", "") or ""),
            ]
            for p in args
        ]
        out += table(["argument", "type", "required", "default", "description"], rows)
        out.append("")
    if opts:
        out += table(["option", "type", "required", "default", "description"], _option_rows(opts))
        out.append("")
    if _is_group(cmd):
        subs = _subcommands(cmd)
        out += table(
            ["subcommand", "summary"],
            ([f"[{code(n)}](#{anchor(title + ' ' + n)})", cell(_help_first_line(c))] for n, c in subs),
        )
        out.append("")
        for n, c in subs:
            out += _command_section([*path, n], c, level + 1)
    return out


def render_cli() -> str:
    from typer.main import get_command

    from hpclab.cli import common
    from hpclab.cli.main import app
    from hpclab.domain.ids import PREFIXES

    root = get_command(app)
    id_kinds = ", ".join(f"`{prefix}_` {kind}" for kind, prefix in PREFIXES.items())
    commands = _subcommands(root)
    panels: dict[str, list[tuple[str, Any]]] = {}
    for n, c in commands:
        panel = (
            "Command groups"
            if _is_group(c)
            else (getattr(c, "rich_help_panel", None) or "Setup and plumbing")
        )
        panels.setdefault(panel, []).append((n, c))

    out: list[str] = [
        "# CLI reference",
        "",
        GENERATED_NOTE,
        "",
        "`hpclab` is the command line of HPC Lab. Every command that reads or changes the ledger goes",
        "through the local controller (autostarted on first use), exactly like the MCP tools, so the CLI,",
        "your coding agent and Python clients always see the same state.",
        "",
        "* Default output: the result's summary line, a readable view, then warnings and incomplete-coverage",
        "  notes. `--json` prints the raw result envelope instead (one JSON document on stdout).",
        f"* Ids are prefixed by kind ({id_kinds}). Where a command takes an experiment, its name works",
        "  too (the newest experiment of that name). Slurm job ids are not hpclab ids: `hpclab which",
        "  <job id>` maps one back to its run and attempt.",
        f"* Exit codes: 0 ok · {common.EXIT_ERROR} domain error · {common.EXIT_USAGE} usage error · "
        f"{common.EXIT_CONTROLLER} controller unavailable · {common.EXIT_AUTH} authentication required.",
        "",
        "## Global options",
        "",
        "Given before the command, e.g. `hpclab --json runs --experiment <experiment>`.",
        "",
    ]
    global_opts = [p for p in root.params if _is_option(p) and _visible(p) and p.name != "help"]
    out += table(["option", "type", "default", "description"], _option_rows(global_opts, with_required=False))
    out += ["", "## Commands", ""]
    order = ["Setup and plumbing", "Experiments", "Runs", "Results", "Lab", "Setup", "Command groups"]
    for panel in [*order, *sorted(set(panels) - set(order))]:
        if panel not in panels:
            continue
        out += [f"**{panel}**", ""]
        out += table(
            ["command", "summary"],
            ([f"[{code(n)}](#{anchor('hpclab ' + n)})", cell(_help_first_line(c))] for n, c in panels[panel]),
        )
        out.append("")
    out += ["## Command reference", ""]
    for n, c in commands:
        out += _command_section(["hpclab", n], c, 3)
    return "\n".join(out).rstrip() + "\n"


