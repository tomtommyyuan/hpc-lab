def generated() -> dict[Path, str]:
    return {TOOLS_MD: render_tools(), CLI_MD: render_cli()}


def stale_files() -> list[Path]:
    stale = []
    for path, text in generated().items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != text:
            stale.append(path)
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="exit 1 if a generated file is stale")
    args = parser.parse_args(argv)
    if args.check:
        stale = stale_files()
        for p in stale:
            print(f"stale: {p.relative_to(REPO)} (run: uv run python scripts/gen_docs.py)", file=sys.stderr)
        return 1 if stale else 0
    for path, text in generated().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        old = path.read_text(encoding="utf-8") if path.is_file() else None
        if old != text:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO)}")
        else:
            print(f"unchanged {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
