def _annotations(spec: Any) -> str:
    flags = []
    flags.append("read-only" if spec.read_only else "mutating")
    if spec.destructive:
        flags.append("destructive")
    flags.append("idempotent" if spec.idempotent else "not idempotent")
    flags.append("open-world" if spec.open_world else "closed-world")
    return " · ".join(flags)


def render_tools() -> str:
    from hpclab.api.envelope import Envelope
    from hpclab.domain.errors import RETRYABLE, ErrorCode
    from hpclab.mcp.catalog import SERVER_INSTRUCTIONS, TOOLS
    from hpclab.mcp.server import PROMPTS, RESOURCES, input_schema, output_schema
    from hpclab.services.app import METHODS, build_registry

    registry = build_registry(strict=True)
    targets = {e.name: e.target for e in METHODS}
    tool_methods = {t.method: t.name for t in TOOLS}
    resource_methods: dict[str, list[str]] = {}
    for r in RESOURCES:
        resource_methods.setdefault(r.method, []).append(r.template)

    out: list[str] = [
        "# MCP tools, resources and prompts",
        "",
        GENERATED_NOTE,
        "",
        "The `hpclab mcp serve` server (stdio) exposes the tools, resources and prompts below. It is a thin",
        "frontend: every call is forwarded to the local controller, which validates it with the same",
        "schemas, runs the service and returns an envelope. Input schemas are derived from the service",
        "signatures; parameter prose comes from `src/hpclab/mcp/catalog.py`.",
        "",
        "* `structuredContent` of a tool result is the complete envelope; the text block is a short rendering",
        "  (summary, the ids needed for the next call, warnings, `Next:` suggestions).",
        "* Mutations take an `idempotency_key`: retrying with the same key and arguments returns the stored",
        "  result; the same key with other arguments is `idempotency_conflict`. Mutations of versioned state",
        "  (attempts, workflows) also take `expected_version`.",
        "* Annotations (read-only, destructive, ...) are UI hints for the client, never authorization: the",
        "  runtime still checks idempotency, the execution claim, live job identity and the budget.",
        "* Lists default to 20 items (max 100); text reads default to 32 KiB (max 64 KiB).",
        "",
        "Contents: [server instructions](#server-instructions) · [result envelope](#result-envelope) ·",
        f"[error codes](#error-codes) · [tools ({len(TOOLS)})](#tools) · [resources](#resources) ·",
        f"[prompts ({len(PROMPTS)})](#prompts) · [controller methods](#controller-methods)",
        "",
        "## Server instructions",
        "",
        "Sent to the client at initialization (`instructions`):",
        "",
        "```text",
        SERVER_INSTRUCTIONS,
        "```",
        "",
        "## Result envelope",
        "",
    ]
    env_schema = Envelope[Any].model_json_schema()
    env_rows = []
    for name, prop in env_schema["properties"].items():
        doc = ENVELOPE_FIELD_DOCS.get(name)
        if doc is None:
            raise SystemExit(f"gen_docs: envelope field {name!r} has no entry in ENVELOPE_FIELD_DOCS")
        env_rows.append([code(name), cell(type_of(prop)), cell(doc)])
    out += table(["field", "type", "meaning"], env_rows)
    coverage = env_schema.get("$defs", {}).get("SourceStatus", {})
    statuses = (coverage.get("properties") or {}).get("status", {}).get("enum") or []
    out += [
        "",
        "`coverage.sources[]` entries are `{name, status, observed_at, detail}` with status "
        + ", ".join(code(s) for s in statuses)
        + ". Anything but `ok`, `cached` or `skipped` makes `coverage.complete` false: an empty list with",
        'incomplete coverage is *not* "nothing exists".',
        "",
        "## Error codes",
        "",
    ]
    err_rows = []
    for ec in ErrorCode:
        doc = ERROR_CODE_DOCS.get(ec.value)
        if doc is None:
            raise SystemExit(f"gen_docs: error code {ec.value!r} has no entry in ERROR_CODE_DOCS")
        err_rows.append([code(ec.value), "yes" if ec in RETRYABLE else "", cell(doc)])
    out += table(["code", "retryable", "meaning"], err_rows)

    # -- tools ------------------------------------------------------------------
    out += ["", "## Tools", ""]
    out += table(
        ["tool", "title", "annotations"],
        ([f"[{code(t.name)}](#{anchor(t.name)})", cell(t.title), cell(_annotations(t))] for t in TOOLS),
    )
    for spec in TOOLS:
        if spec.method not in registry.methods:
            raise SystemExit(f"gen_docs: tool {spec.name} -> method {spec.method} is not registered")
        ins = input_schema(spec, registry)
        outs = output_schema(spec, registry)
        out += [
            "",
            f"### {spec.name}",
            "",
            f"**{spec.title}** — {_annotations(spec)} · controller method {code(spec.method)} "
            f"({code(targets.get(spec.method, '?'))})",
            "",
            spec.description,
            "",
            "**Parameters**",
            "",
        ]
        rows = property_rows(ins)
        if rows:
            out += table(["name", "type", "required", "default", "description"], rows)
        else:
            out.append("None.")
        defs = ins.get("$defs") or {}
        for name in reachable_defs(ins.get("properties"), defs):
            d = defs[name]
            out += ["", f"`{name}`" + (f": {cell(d['description'])}" if d.get("description") else ""), ""]
            if d.get("properties"):
                out += table(["field", "type", "required", "default", "description"], property_rows(d))
            else:
                out.append(f"{cell(type_of(d))}")
        data = outs["properties"]["data"]
        data_schema = next(
            (s for s in data.get("anyOf", []) if isinstance(s, dict) and s.get("properties")), None
        )
        out += ["", "**Result `data` fields**", ""]
        if data_schema is None:
            out.append("Not typed.")
        else:
            req = set(data_schema.get("required") or [])
            fields = [
                f"{code(n)}{'' if n in req else '?'}: {type_of(p)}"
                for n, p in (data_schema.get("properties") or {}).items()
            ]
            out.append(", ".join(fields) + ".")
            out += ["", "(`?` = optional. Nested types are in the tool's `outputSchema`.)"]

    # -- resources ----------------------------------------------------------------
    out += [
        "",
        "## Resources",
        "",
        "Read with `resources/read`. They share the tools' size limits; text resources that were cut",
        "end with a visible truncation marker. `resources/list` returns `hpclab://experiments` plus the",
        "20 most recent experiments, so a new session can find experiment ids.",
        "",
    ]
    res_rows = [[code(r.template), code(r.mime_type), code(r.method), cell(r.description)] for r in RESOURCES]
    out += table(["URI", "MIME type", "controller method", "content"], res_rows)

    # -- prompts ------------------------------------------------------------------
    out += [
        "",
        "## Prompts",
        "",
        "For MCP clients without skill support: each prompt returns the matching skill from `skills/`",
        "(the same text `hpclab skills install` copies into `~/.claude/skills`).",
        "",
    ]
    prompt_rows = []
    for name, (skill, desc, args) in PROMPTS.items():
        arg_s = ", ".join(f"{code(a.name)}{'' if a.required else '?'}" for a in args)
        prompt_rows.append([code(name), code(skill), cell(arg_s), cell(desc)])
    out += table(["prompt", "skill", "arguments (`?` optional)", "description"], prompt_rows)

    # -- controller methods -------------------------------------------------------
    out += [
        "",
        "## Controller methods",
        "",
        "Every public method of the controller (`hpclab.services.app.METHODS`). The CLI calls the same",
        "methods; methods without a tool are CLI-only (for example `attempt_resolve`, a human decision) or",
        "back a resource.",
        "",
    ]
    m_rows = []
    for e in METHODS:
        exposed = []
        if e.name in tool_methods:
            exposed.append(f"tool {code(tool_methods[e.name])}")
        exposed += [f"resource {code(t)}" for t in resource_methods.get(e.name, [])]
        m_rows.append(
            [
                code(e.name),
                code(e.target),
                "yes" if e.mutation else "",
                cell(", ".join(exposed) or "CLI only"),
            ]
        )
    out += table(["method", "service function", "mutation", "exposed as"], m_rows)
    return "\n".join(out).rstrip() + "\n"


