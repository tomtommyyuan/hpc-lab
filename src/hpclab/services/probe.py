def _spec_params(spec_json: str | None) -> dict[str, Any]:
    spec = jload(spec_json, {}) or {}
    params = spec.get("params") if isinstance(spec, dict) else None
    return params if isinstance(params, dict) else {}


def find_probe_runs(
    reader: Database | Tx,
    *,
    experiment_id: str,
    target_run_id: str,
    manifest_digest: str,
    checkpoint_dir: str | None = None,
) -> list[dict[str, Any]]:
    """Probe Runs (oldest first) created for exactly this checkpoint manifest of this Run with the
    current probe version. A probe of another manifest, Run or probe version never counts, and
    with ``checkpoint_dir`` neither does a probe of another directory: a copied checkpoint has the
    same manifest digest but its own bytes, which only its own probe has hashed."""
    rows = reader.all(
        "SELECT * FROM runs WHERE experiment_id=? AND kind='probe' ORDER BY created_at, run_id",
        (experiment_id,),
    )
    want_dir = checkpoint_dir.rstrip("/") if checkpoint_dir is not None else None
    out: list[dict[str, Any]] = []
    for r in rows:
        p = _spec_params(r["spec_json"])
        if (
            p.get("probe") == PROBE_PARAM_KIND
            and p.get("target_run_id") == target_run_id
            and p.get("checkpoint_manifest_digest") == manifest_digest
            and str(p.get("probe_version")) == PROBE_VERSION
            and (want_dir is None or str(p.get("checkpoint_dir") or "").rstrip("/") == want_dir)
        ):
            out.append(r)
    return out


@dataclass(frozen=True)
class ProbeResult:
    ok: bool
    load_checked: bool
    errors: list[str]
    manifest_digest: str | None


def parse_probe_result(text: str | bytes, *, manifest_digest: str) -> ProbeResult:
    """Interpret ``probe.json``. Anything unexpected (other schema/version, other manifest, bad
    JSON) is a failed probe, never a pass."""
    try:
        doc = json.loads(text)
    except (ValueError, RecursionError):
        return ProbeResult(False, False, ["probe.json is not valid JSON"], None)
    if not isinstance(doc, dict):
        return ProbeResult(False, False, ["probe.json is not an object"], None)
    errors = [str(e)[:300] for e in (doc.get("errors") or []) if isinstance(e, str)][:10]
    got = doc.get("manifest_digest") if isinstance(doc.get("manifest_digest"), str) else None
    if doc.get("schema") != PROBE_SCHEMA or str(doc.get("probe_version")) != PROBE_VERSION:
        return ProbeResult(
            False, False, ["probe.json has an unexpected schema or probe version", *errors], got
        )
    if got != manifest_digest:
        return ProbeResult(
            False,
            bool(doc.get("load_checked")),
            [f"probe checked manifest {got}, not {manifest_digest}", *errors],
            got,
        )
    ok = doc.get("ok") is True and not errors
    return ProbeResult(ok, bool(doc.get("load_checked")), errors, got)


ProbeState = Literal["none", "not_submitted", "running", "passed", "failed", "unverified"]


@dataclass(frozen=True)
class ProbeStatus:
    state: ProbeState
    run_id: str | None = None
    attempt_id: str | None = None
    exec_plan_hash: str | None = None
    plan_id: str | None = None
    detail: str | None = None
    load_checked: bool = False
    errors: tuple[str, ...] = ()


def probe_status(
    ctx: ServiceContext, *, probe_runs: list[dict[str, Any]], manifest_digest: str, cluster_id: str
) -> ProbeStatus:
    """Best status among the probe Runs for one manifest (passed > running > not_submitted >
    unverified > failed). Reads ``probe.json`` of a COMPLETED probe (one bounded remote read)."""
    if not probe_runs:
        return ProbeStatus("none")
    best: ProbeStatus | None = None
    order = {"passed": 0, "running": 1, "not_submitted": 2, "unverified": 3, "failed": 4, "none": 5}
    for run in probe_runs:
        st = _one_probe_status(ctx, run, manifest_digest=manifest_digest, cluster_id=cluster_id)
        if best is None or order[st.state] < order[best.state]:
            best = st
    assert best is not None
    return best


def _one_probe_status(
    ctx: ServiceContext, run: dict[str, Any], *, manifest_digest: str, cluster_id: str
) -> ProbeStatus:
    run_id = run["run_id"]
    base = {
        "run_id": run_id,
        "exec_plan_hash": run.get("current_exec_plan_hash"),
        "plan_id": run.get("plan_id"),
    }
    attempts = ctx.db.all("SELECT * FROM attempts WHERE run_id=? ORDER BY seq", (run_id,))
    if not attempts:
        return ProbeStatus("not_submitted", detail="probe run created but not submitted yet", **base)
    for a in reversed(attempts):
        phase = a["phase"]
        if phase in {p.value for p in SLOT_HOLDING_PHASES}:
            return ProbeStatus(
                "running", attempt_id=a["attempt_id"], detail=f"probe attempt is {phase}", **base
            )
    done = [
        a
        for a in attempts
        if a["phase"] == AttemptPhase.TERMINAL.value
        and a["scheduler_state"] == SchedulerState.COMPLETED.value
        and (a["exit_code"] in (0, None))
    ]
    if not done:
        last = attempts[-1]
        return ProbeStatus(
            "failed",
            attempt_id=last["attempt_id"],
            detail=f"probe attempt ended {last['phase']}/{last['scheduler_state']} (exit {last['exit_code']})",
            **base,
        )
    a = done[-1]
    if a["result_state"] in ("invalid", "incomplete"):
        return ProbeStatus(
            "failed", attempt_id=a["attempt_id"], detail=f"probe outputs are {a['result_state']}", **base
        )
    path = f"{str(a['remote_dir']).rstrip('/')}/outputs/{PROBE_OUTPUT_FILE}"
    try:
        transport = ctx.clusters.transport(a["cluster_id"] or cluster_id)
        rr = transport.read_range(path, 0, MAX_PROBE_JSON_BYTES, timeout=ctx.settings.request_deadline_s)
    except AuthRequiredError:
        raise
    except FileNotFoundError:
        return ProbeStatus(
            "failed", attempt_id=a["attempt_id"], detail=f"{PROBE_OUTPUT_FILE} is missing", **base
        )
    except TransportError as exc:
        return ProbeStatus(
            "unverified",
            attempt_id=a["attempt_id"],
            detail=f"could not read {PROBE_OUTPUT_FILE}: {exc.message}",
            **base,
        )
    if not rr.eof:
        return ProbeStatus(
            "failed", attempt_id=a["attempt_id"], detail=f"{PROBE_OUTPUT_FILE} is too large", **base
        )
    res = parse_probe_result(rr.data, manifest_digest=manifest_digest)
    if not res.ok:
        return ProbeStatus(
            "failed",
            attempt_id=a["attempt_id"],
            detail="; ".join(res.errors[:3]) or "probe reported failure",
            load_checked=res.load_checked,
            errors=tuple(res.errors),
            **base,
        )
    return ProbeStatus(
        "passed",
        attempt_id=a["attempt_id"],
        detail="digests verified on a compute node"
        + ("; files loaded" if res.load_checked else "; load not checked (torch unavailable)"),
        load_checked=res.load_checked,
        **base,
    )


