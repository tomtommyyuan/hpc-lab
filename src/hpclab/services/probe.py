"""Checkpoint load probes: the compute-node half of "is this checkpoint usable for resume?".

``adapters.checkpoint`` validates checkpoint *metadata* on the controller (manifest, sizes, config
compatibility). Whether the files actually hash to the manifest digests and deserialize can only
be established on a compute node — hashing tens of GB or unpickling on the login node is exactly
what site policies forbid. ``run_recover`` therefore creates an ordinary Run of kind ``probe``
whose program is the built-in ``hpclab_ckpt_probe.py`` (passed as ``python -c <source>`` so it
needs nothing from the code snapshot), and only offers a ``resume`` plan once such a probe run
COMPLETED and its ``probe.json`` confirms the *same* manifest digest and probe version.

The probe:

* re-reads ``hpclab-ckpt.json`` and recomputes its canonical digest (same canonical JSON as
  ``hpclab.domain.hashing``) - a manifest that changed after the recovery check fails the probe;
* checks every listed file exists, has the manifest size and the manifest ``sha256``;
* if ``torch`` is importable, ``torch.load(map_location="cpu")`` each ``.pt/.pth/.bin/.ckpt/.pkl``
  file (``weights_only=True`` first, then ``False`` - it is the researcher's own checkpoint loaded
  in the researcher's own job, exactly what the program will do on resume); ``.safetensors`` files
  are opened with ``safetensors`` when available;
* writes ``$HPCLAB_OUTPUT_DIR/probe.json`` atomically and exits 0 (passed) or 2 (checks failed).

Without torch the probe still verifies digests and records ``load_checked: false``; recovery
reports that as a warning rather than a pass of loadability.
"""

