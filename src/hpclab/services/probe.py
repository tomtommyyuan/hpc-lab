PROBE_VERSION = "1"
PROBE_SCHEMA = "hpclab.ckpt-probe/v1"
PROBE_SCRIPT_NAME = "hpclab_ckpt_probe.py"
PROBE_OUTPUT_NAME = "probe"
PROBE_OUTPUT_FILE = "probe.json"
PROBE_PARAM_KIND = "checkpoint_load"
MAX_PROBE_JSON_BYTES = 256 * 1024

# NOTE: this source is passed as ONE argv element; the job wrapper substitutes runtime placeholders
# (``{output_dir}`` & co.) in argv, so it must never contain such a token (a unit test enforces it).
PROBE_SOURCE = r"""# hpclab_ckpt_probe.py (hpclab checkpoint load probe, version 1). Generated by hpclab.
import hashlib, json, os, sys, time
SCHEMA = "hpclab.ckpt-probe/v1"
VERSION = "1"
MANIFEST = "hpclab-ckpt.json"
LOADABLE = (".pt", ".pth", ".bin", ".ckpt", ".pkl")
MAX_ERRORS = 50


def canonical(obj):
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False)


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        while True:
            chunk = fh.read(1 << 20)
            if not chunk:
                break
            h.update(chunk)
    return "sha256:" + h.hexdigest()


def norm_digest(value):
    if not isinstance(value, str):
        return None
    v = value.strip().lower()
    if v.startswith("sha256:"):
        v = v[7:]
    return "sha256:" + v if len(v) == 64 else None


def safe_rel(path):
    if not path or path.startswith("/") or "\\" in path or "\x00" in path:
        return False
    norm = os.path.normpath(path)
    return norm not in (".", "..") and not norm.startswith("../")


def try_load(torch, full):
    # weights_only=True first; False is what the program's own resume does for full training state;
    # the bare call covers old torch versions without the keyword.
    last = None
    for kwargs in ({"weights_only": True}, {"weights_only": False}, {}):
        try:
            torch.load(full, map_location="cpu", **kwargs)
            return kwargs.get("weights_only"), None
        except Exception as exc:
            last = exc
    return None, "%s: %s" % (type(last).__name__, str(last)[:300])


def main(argv):
    ckpt_dir = argv[1] if len(argv) > 1 else ""
    expected = argv[2] if len(argv) > 2 else ""
    out_dir = os.environ.get("HPCLAB_OUTPUT_DIR") or os.getcwd()
    errors = []
    report = {"schema": SCHEMA, "probe_version": VERSION, "checkpoint_dir": ckpt_dir,
              "expected_manifest_digest": expected, "manifest_digest": None, "step": None,
              "files": [], "errors": errors, "load_checked": False, "torch_version": None,
              "host": os.uname()[1] if hasattr(os, "uname") else None, "started_at": time.time()}
    manifest = None
    try:
        with open(os.path.join(ckpt_dir, MANIFEST), "rb") as fh:
            manifest = json.loads(fh.read().decode("utf-8"))
        report["manifest_digest"] = "sha256:" + hashlib.sha256(canonical(manifest).encode("utf-8")).hexdigest()
    except Exception as exc:
        errors.append("manifest unreadable: %s: %s" % (type(exc).__name__, str(exc)[:300]))
    if manifest is not None and report["manifest_digest"] != expected:
        errors.append("manifest digest %s differs from the checked %s (the checkpoint changed)"
                      % (report["manifest_digest"], expected))
    files = manifest.get("files") if isinstance(manifest, dict) else None
    if isinstance(manifest, dict):
        report["step"] = manifest.get("step")
        if manifest.get("complete") is not True:
            errors.append("manifest is not marked complete")
    if manifest is not None and (not isinstance(files, list) or not files):
        errors.append("manifest lists no files")
        files = []
    torch = None
    try:
        import torch  # noqa: F401
        report["torch_version"] = getattr(torch, "__version__", None)
    except Exception as exc:
        report["torch_import_error"] = "%s: %s" % (type(exc).__name__, str(exc)[:200])
        torch = None
    loads = 0
    for entry in files or []:
        rel = entry.get("path") if isinstance(entry, dict) else None
        rec = {"path": rel, "exists": False, "size": None, "size_ok": None, "sha256_ok": None, "loaded": None}
        report["files"].append(rec)
        if not isinstance(rel, str) or not safe_rel(rel):
            errors.append("unsafe or malformed file entry: %r" % (rel,))
            continue
        full = os.path.join(ckpt_dir, rel)
        if not os.path.isfile(full):
            errors.append("%s is missing" % rel)
            continue
        rec["exists"] = True
        rec["size"] = os.path.getsize(full)
        want_size = entry.get("size")
        if isinstance(want_size, int) and not isinstance(want_size, bool):
            rec["size_ok"] = rec["size"] == want_size
            if not rec["size_ok"]:
                errors.append("%s is %d bytes, manifest says %d" % (rel, rec["size"], want_size))
                continue
        want = norm_digest(entry.get("sha256"))
        if want is not None:
            have = sha256_file(full)
            rec["sha256_ok"] = have == want
            if not rec["sha256_ok"]:
                errors.append("%s content digest differs from the manifest" % rel)
                continue
        lower = rel.lower()
        if torch is not None and lower.endswith(LOADABLE):
            weights_only, err = try_load(torch, full)
            rec["loaded"] = err is None
            rec["weights_only"] = weights_only
            loads += 1 if err is None else 0
            if err is not None:
                errors.append("%s did not load: %s" % (rel, err))
        elif lower.endswith(".safetensors"):
            try:
                from safetensors import safe_open
                with safe_open(full, framework="numpy") as st:
                    rec["tensors"] = len(list(st.keys()))
                rec["loaded"] = True
                loads += 1
            except ImportError:
                pass
            except Exception as exc:
                rec["loaded"] = False
                errors.append("%s did not open: %s: %s" % (rel, type(exc).__name__, str(exc)[:300]))
    report["load_checked"] = loads > 0
    del errors[MAX_ERRORS:]
    report["ok"] = manifest is not None and not errors
    report["finished_at"] = time.time()
    os.makedirs(out_dir, exist_ok=True)
    target = os.path.join(out_dir, "probe.json")
    tmp = target + ".tmp.%d" % os.getpid()
    with open(tmp, "w") as fh:
        json.dump(report, fh, sort_keys=True)
        fh.flush()
        os.fsync(fh.fileno())
    os.replace(tmp, target)
    sys.stdout.write("[hpclab-probe] ok=%s files=%d loaded=%d errors=%d\n"
                     % (report["ok"], len(report["files"]), loads, len(errors)))
    for line in errors[:10]:
        sys.stderr.write("[hpclab-probe] %s\n" % line)
    return 0 if report["ok"] else 2


sys.exit(main(sys.argv))
"""


def _check_source() -> None:
    bad = [p for p in RUNTIME_PLACEHOLDERS if "{" + p + "}" in PROBE_SOURCE]
    if bad:  # pragma: no cover - guarded by a unit test; a programming error, not user input
        raise RuntimeError(f"probe source contains runtime placeholders {bad}")


_check_source()


