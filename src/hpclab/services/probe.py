def probe_run_spec(
    source: RunSpec,
    *,
    target_run_id: str,
    checkpoint_dir: str,
    manifest_digest: str,
    artifact_id: str | None,
    step: int | None = None,
) -> RunSpec:
    """The probe Run: same code snapshot and runtime (venv, setup, env) as the Run it serves, so
    "loads here" means "loads in the environment the resume will use". Never a scientific Run:
    ``kind='probe'``, no seed, no evaluation."""
    argv = [source.runtime.python, "-c", PROBE_SOURCE, checkpoint_dir, manifest_digest]
    params: dict[str, Any] = {
        "probe": PROBE_PARAM_KIND,
        "probe_version": PROBE_VERSION,
        "target_run_id": target_run_id,
        "checkpoint_dir": checkpoint_dir,
        "checkpoint_manifest_digest": manifest_digest,
        "checkpoint_artifact_id": artifact_id,
        "checkpoint_step": step,
    }
    return RunSpec(
        experiment=source.experiment,
        kind="probe",
        code=source.code,
        entrypoint=EntrypointSpec(argv=[source.runtime.python, "-c", PROBE_SCRIPT_NAME], workdir="."),
        argv=argv,
        params=params,
        cell={"probe_of": target_run_id, "checkpoint": short(manifest_digest)},
        seed=None,
        inputs=[],
        runtime=source.runtime,
        outputs=[
            OutputDecl(
                name=PROBE_OUTPUT_NAME,
                path="{output_dir}/" + PROBE_OUTPUT_FILE,
                role="other",
                kind="file",
                format="json",
                required=True,
            )
        ],
        evaluation=None,
        derived_from=None,
    )


def probe_resources(
    base: ResourceSpec, *, checkpoint_bytes: int | None, largest_file_bytes: int | None
) -> ResourceSpec:
    """CPU-only, short: hashing at ~200 MB/s plus deserializing the largest file into RAM.

    Keeps the base plan's partition/account/qos (a site may reject CPU jobs on a GPU partition:
    then run_recover's probe plan can be re-planned with adjust_resources on the probe run).
    """
    total = max(0, checkpoint_bytes or 0)
    largest = max(0, largest_file_bytes or 0)
    minutes = 15 + math.ceil(total / (200 * 1024**2) / 60) * 2
    minutes = min(minutes, 240)
    mem_gib = max(8, math.ceil(largest * 1.5 / 1024**3) + 2)
    mem_gib = min(mem_gib, 256)
    return ResourceSpec(
        partition=base.partition,
        account=base.account,
        qos=base.qos,
        gpus=0,
        gpu_type=None,
        cpus=2,
        mem=f"{mem_gib}G",
        time=f"{minutes // 60:02d}:{minutes % 60:02d}:00",
        nodes=1,
        ntasks_per_node=1,
        exclude_nodes=list(base.exclude_nodes),
        constraint=None,
        extra_sbatch=[],
    )


