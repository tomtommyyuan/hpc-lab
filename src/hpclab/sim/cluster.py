"""``SimCluster``: create, inspect, fault-inject and tear down a simulated Slurm cluster.

Layout of ``<sim_root>``::

    bin/          fake sbatch/squeue/... shims (exec ``python -m hpclab.sim.cli <cmd>``)
    gpu-bin/      fake ``nvidia-smi``: on the PATH of jobs running on GPU nodes only (like a
                  real cluster, where the login node has no GPU tools)
    fs/           suggested "remote" filesystem root (any absolute path works)
    config.json   SimConfig
    state.db      SQLite state shared by every fake command and job runner
    spool/        per-job copies of submitted batch scripts
    logs/         job runner logs (debugging the simulator itself)

The simulator is the *external ground truth* for tests: ``jobs()`` lists what sbatch really
accepted, independent of what hpclab's own ledger believes.
"""

from __future__ import annotations

import contextlib
import math
import os
import shlex
import signal
import subprocess
import sys
import time
from dataclasses import asdict
from pathlib import Path
from typing import Any

import hpclab
from hpclab.sim.config import SimConfig, SimFaults
from hpclab.sim.state import TERMINAL_STATES, SimJob, SimState, pid_alive, safe_killpg

SHIM_COMMANDS = ("sbatch", "squeue", "sacct", "scancel", "sinfo", "sacctmgr", "sstat", "srun", "scontrol")
GPU_SHIM_COMMANDS = ("nvidia-smi",)
_JOB_SUMMARY_FIELDS = (
    "job_id",
    "array_job_id",
    "array_task_id",
    "name",
    "user",
    "account",
    "partition",
    "qos",
    "state",
    "raw_state",
    "reason",
    "submit_time",
    "start_time",
    "end_time",
    "time_limit_s",
    "exit_code",
    "exit_signal",
    "node_list",
    "gpus_per_node",
    "gpu_type",
    "comment",
    "work_dir",
    "stdout_path",
    "stderr_path",
    "submit_line",
    "fate",
    "dependency",
)


def job_summary(job: SimJob) -> dict[str, Any]:
    data = asdict(job)
    out = {k: data[k] for k in _JOB_SUMMARY_FIELDS}
    out["display_id"] = job.display_id
    out["total_gpus"] = job.total_gpus
    return out


def _shim(root: Path, command: str) -> str:
    package_parent = str(Path(hpclab.__file__).resolve().parent.parent)
    return (
        "#!/bin/sh\n"
        f"# Generated by hpclab.sim: fake '{command}' backed by the simulator at {root}\n"
        f"HPCLAB_SIM_ROOT={shlex.quote(str(root))}\n"
        "export HPCLAB_SIM_ROOT\n"
        f"PYTHONPATH={shlex.quote(package_parent)}${{PYTHONPATH:+:$PYTHONPATH}}\n"
        "export PYTHONPATH\n"
        f'exec {shlex.quote(sys.executable)} -m hpclab.sim.cli {command} "$@"\n'
    )


def _install_shims(bin_dir: Path, root: Path, commands: tuple[str, ...]) -> None:
    bin_dir.mkdir(parents=True, exist_ok=True)
    for command in commands:
        path = bin_dir / command
        content = _shim(root, command)
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        tmp = bin_dir / f".{command}.{os.getpid()}.tmp"
        tmp.write_text(content, encoding="utf-8")
        tmp.chmod(0o755)
        tmp.replace(path)


def _install_bin(root: Path) -> Path:
    bin_dir = root / "bin"
    _install_shims(bin_dir, root, SHIM_COMMANDS)
    _install_shims(root / "gpu-bin", root, GPU_SHIM_COMMANDS)
    return bin_dir


def _is_sim_process(pid: int, needle: str) -> bool:
    """Guard against pid reuse before SIGKILL: the process command line must mention the sim."""
    try:
        out = subprocess.run(
            ["ps", "-o", "command=", "-p", str(pid)], capture_output=True, text=True, timeout=5, check=False
        )
    except (OSError, subprocess.TimeoutExpired):
        return False
    return out.returncode == 0 and needle in out.stdout


class SimCluster:
    """Handle on one simulator root. Cheap to construct; all state lives on disk."""

    def __init__(self, root: Path) -> None:
        self.root = Path(root)
        self.state = SimState(self.root)

    @staticmethod
    def ensure(sim_root: Path, config: SimConfig | None = None) -> SimCluster:
        """Create (or refresh) the simulator at ``sim_root``. Idempotent.

        ``config=None`` keeps an existing config (or writes the default one); a given config
        replaces it. Shims are rewritten if the interpreter path changed.
        """
        # Resolved so paths derived from getcwd() in fake commands match the ones callers use.
        root = Path(sim_root).resolve()
        for sub in ("fs", "spool", "logs"):
            (root / sub).mkdir(parents=True, exist_ok=True)
        state = SimState(root)
        if config is not None:
            config.validate().save(state.config_path)
        elif not state.config_path.exists():
            SimConfig().save(state.config_path)
        state.init_schema()
        _install_bin(root)
        return SimCluster(root)

    # -- layout -------------------------------------------------------------------
    @property
    def bin_dir(self) -> Path:
        return self.root / "bin"

    @property
    def fs_root(self) -> Path:
        return self.root / "fs"

    @property
    def config(self) -> SimConfig:
        return self.state.config

    @property
    def user(self) -> str:
        return self.config.user

    def env(self) -> dict[str, str]:
        """Environment for running the fake commands directly (PATH + HPCLAB_SIM_ROOT)."""
        env = dict(os.environ)
        env["PATH"] = os.pathsep.join([str(self.bin_dir), env.get("PATH", "")])
        env["HPCLAB_SIM_ROOT"] = str(self.root)
        return env

    def run(
        self, *argv: str, cwd: str | Path | None = None, timeout: float = 30.0
    ) -> subprocess.CompletedProcess[str]:
        """Run a fake Slurm command as a subprocess (test/debug helper)."""
        return subprocess.run(
            list(argv), env=self.env(), cwd=cwd, capture_output=True, text=True, timeout=timeout, check=False
        )

    # -- faults -------------------------------------------------------------------
    def set_faults(self, **faults: Any) -> SimFaults:
        """Set fault switches (see ``SimFaults``); unknown names raise ValueError."""
        return self.state.set_faults(**faults)

    def clear_faults(self) -> None:
        self.state.clear_faults()

    def faults(self) -> SimFaults:
        return self.state.faults()

    # -- introspection -------------------------------------------------------------
    def jobs(self) -> list[dict[str, Any]]:
        """Every job sbatch ever accepted (ground truth), oldest first."""
        return [job_summary(j) for j in self.state.jobs()]

    def job(self, job_id: int | str) -> dict[str, Any] | None:
        token = str(job_id)
        for j in self.state.jobs():
            if j.display_id == token or str(j.job_id) == token:
                return job_summary(j)
        return None

    def wait_idle(self, timeout: float) -> bool:
        """Wait until no (real) job is pending or running. False on timeout."""
        deadline = time.monotonic() + timeout
        while True:
            self.state.reap()
            with self.state.reader() as conn:
                active = [j for j in self.state.load_jobs(conn, active_only=True) if not j.synthetic]
            if not active:
                return True
            if time.monotonic() >= deadline:
                return False
            time.sleep(0.05)

    def wait_for(
        self, job_id: int | str, states: set[str] | frozenset[str], timeout: float
    ) -> dict[str, Any] | None:
        """Poll until the job reaches one of ``states``; the job summary, or None on timeout."""
        deadline = time.monotonic() + timeout
        while True:
            job = self.job(job_id)
            if job is not None and job["state"] in states:
                return job
            if time.monotonic() >= deadline:
                return None
            time.sleep(0.05)

    def set_node_state(self, node: str, state: str, reason: str | None = None) -> None:
        """Admin node state: ``up``/``resume``, ``drain`` (with reason) or ``down``."""
        self.state.set_node_state(node, state, reason)

    def inject_job(
        self,
        *,
        submit_time: float,
        state: str = "COMPLETED",
        start_time: float | None = None,
        end_time: float | None = None,
        user: str | None = None,
        account: str | None = None,
        partition: str | None = None,
        qos: str | None = None,
        name: str = "injected",
        gpus: int = 0,
        gpu_type: str | None = None,
        nodes: int = 1,
        cpus: int = 1,
        time_limit_s: int | None = 3600,
        exit_code: int = 0,
        exit_signal: int = 0,
        node_list: list[str] | None = None,
        segments: list[dict[str, Any]] | None = None,
        comment: str | None = None,
        raw_state: str | None = None,
        reason: str | None = None,
    ) -> int:
        """Record a synthetic job (accounting history, another user's job) and return its id.

        It is never executed, scheduled or reaped; squeue/sacct/sinfo show it like any other job
        (a RUNNING one holds its GPUs). ``segments`` are earlier requeue segments
        (``{"start", "end", "state", "submit"?, "node_list"?, "exit_code"?, "exit_signal"?}``;
        without ``submit`` a segment shares the job's submit time), which ``sacct --duplicates``
        lists as separate records.
        """
        cfg = self.config
        if state not in TERMINAL_STATES and state not in ("RUNNING", "PENDING"):
            raise ValueError(f"cannot inject a job in state {state!r}")
        part = cfg.partition(partition) if partition else cfg.default_partition()
        if part is None:
            raise ValueError(f"unknown partition {partition!r}")
        started = state != "PENDING" and start_time is not None
        if state == "RUNNING" and start_time is None:
            raise ValueError("a RUNNING job needs start_time")
        if state in TERMINAL_STATES and end_time is None:
            raise ValueError("a terminal job needs end_time")
        chosen = list(node_list or part.nodes[:nodes]) if started else []
        per_node = math.ceil(gpus / max(1, nodes)) if gpus else 0
        node_cfg = cfg.node(chosen[0]) if chosen else cfg.node(part.nodes[0])
        who = user or cfg.user
        job = SimJob(
            job_id=0,
            name=name,
            user=who,
            uid=os.getuid() if who == cfg.user else 60000 + sum(map(ord, who)) % 5000,
            account=account or cfg.default_account,
            partition=part.name,
            qos=qos or cfg.default_qos,
            submit_time=submit_time,
            time_limit_s=time_limit_s,
            nodes=nodes,
            cpus_per_node=max(1, math.ceil(cpus / max(1, nodes))),
            gpus_per_node=per_node,
            gpu_type=gpu_type or (node_cfg.gpu_type if per_node and node_cfg else None),
            state=state,
            raw_state=raw_state,
            reason=reason,
            start_time=start_time if started else (end_time if state in TERMINAL_STATES else None),
            end_time=end_time if state in TERMINAL_STATES else None,
            node_list=chosen,
            exit_code=exit_code if state in TERMINAL_STATES else None,
            exit_signal=exit_signal if state in TERMINAL_STATES else None,
            comment=comment,
            submit_line="sbatch (injected)",
            segments=[dict(seg) for seg in segments or []],
            restart_count=len(segments or []),
            synthetic=True,
        )
        with self.state.tx() as conn:
            if state == "RUNNING":
                job.alloc = self._synthetic_alloc(conn, job)
            job.job_id = self.state.allocate_job_id(conn)
            self.state.put_job(conn, job)
        return job.job_id

    def _synthetic_alloc(self, conn: Any, job: SimJob) -> dict[str, dict[str, Any]]:
        from hpclab.sim.scheduler import node_usage

        use = node_usage(self.state.load_jobs(conn, active_only=True))
        alloc: dict[str, dict[str, Any]] = {}
        for name in job.node_list:
            node = self.config.node(name)
            if node is None:
                raise ValueError(f"unknown node {name!r}")
            taken = use[name].gpus if name in use else set()
            free = [i for i in range(node.gpus) if i not in taken]
            if len(free) < job.gpus_per_node:
                raise ValueError(f"node {name} has only {len(free)} free GPU(s)")
            alloc[name] = {
                "gpus": free[: job.gpus_per_node],
                "cpus": job.cpus_per_node,
                "mem": job.mem_per_node_mb,
            }
        return alloc

    # -- teardown -------------------------------------------------------------------
    def shutdown(self, grace_s: float | None = None) -> list[int]:
        """Stop every live job: pending jobs are cancelled, running ones get the scancel path
        (SIGTERM, KillWait, SIGKILL) and anything still alive after ``grace_s`` is killed.

        Returns the ids of jobs that were still active. Safe to call repeatedly.
        """
        uid = os.getuid()
        now = time.time()
        with self.state.tx() as conn:
            active = self.state.load_jobs(conn, active_only=True)
            for job in active:
                if job.state == "PENDING" or job.synthetic:
                    self.state.finish(conn, job, "CANCELLED", now=now, raw_state=f"CANCELLED by {uid}")
                else:
                    job.cancel_requested, job.cancelled_by = True, uid
                    self.state.put_job(conn, job)
        running = [j for j in active if j.state != "PENDING" and not j.synthetic]
        if not running:
            return [j.job_id for j in active]
        wait = (self.config.kill_wait_s + 1.0) if grace_s is None else grace_s
        deadline = time.monotonic() + wait
        while time.monotonic() < deadline:
            with self.state.reader() as conn:
                if not self.state.load_jobs(conn, active_only=True):
                    return [j.job_id for j in active]
            time.sleep(0.05)
        needle = str(self.root)
        with self.state.tx() as conn:
            for job in self.state.load_jobs(conn, active_only=True):
                if job.pgid and pid_alive(job.pgid) and _is_sim_process(job.pgid, needle):
                    safe_killpg(job.pgid, signal.SIGKILL)
                if job.runner_pid and pid_alive(job.runner_pid) and _is_sim_process(job.runner_pid, needle):
                    with contextlib.suppress(OSError):
                        os.kill(job.runner_pid, signal.SIGKILL)
                self.state.finish(conn, job, "CANCELLED", now=time.time(), raw_state=f"CANCELLED by {uid}")
        return [j.job_id for j in active]
